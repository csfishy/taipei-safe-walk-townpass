"""Build reviewable, self-contained SQL; never connects to a database.

The historical fresh-install SQL stays unchanged. This generator adapts its
functions to the inventoried public PostGIS / extensions pgcrypto installation.
Run with --check to detect stale generated artifacts.
"""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIGRATION = ROOT / 'migrations/20261113000000_upgrade_nearby_backend.sql'
VERIFIER = ROOT / '04_verify_backend.sql'


def build():
    source = (ROOT / '001_nearby_helper.sql').read_text(encoding='utf-8')
    old_verify = (ROOT / '02_verify.sql').read_text(encoding='utf-8')
    before = old_verify[old_verify.index('DO $verify$'):old_verify.index('-- Aggregate counts')]
    before = before.replace('$verify$', '$baseline$')
    # Reuse the exact catalog assertions from the previously deployed four-table spec.
    header = '''-- GENERATED by local_test/generate_upgrade.py. MANUAL ONLY; NOT DEPLOYED.
-- One-time forward upgrade from the 2026-11-13 read-only inventory.
-- No business RPCs are invoked; no data is seeded or purged; no Auth/Cron settings
-- or legacy public RPCs are changed. Not in Supabase's auto-run migrations path.
BEGIN;
SET LOCAL search_path = pg_catalog;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
LOCK TABLE safe_walk_nearby.helper_profiles, safe_walk_nearby.helper_locations,
  safe_walk_nearby.alerts, safe_walk_nearby.alert_deliveries IN ACCESS EXCLUSIVE MODE;
'''
    preflight = '''
DO $environment$
BEGIN
  IF current_user <> pg_get_userbyid((SELECT nspowner FROM pg_namespace
      WHERE oid = 'safe_walk_nearby'::regnamespace)) THEN
    RAISE EXCEPTION 'Run as existing schema owner; do not transfer ownership';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace
      WHERE e.extname='postgis' AND n.nspname='public') OR NOT EXISTS (
      SELECT 1 FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace
      WHERE e.extname='pgcrypto' AND n.nspname='extensions') THEN
    RAISE EXCEPTION 'Expected existing public PostGIS and extensions pgcrypto; do not move extensions';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_proc p WHERE p.pronamespace='public'::regnamespace
      AND left(p.proname,7)='nearby_') THEN
    RAISE EXCEPTION 'New RPC already exists; stop on repeat application or drift';
  END IF;
END $environment$;
ALTER TABLE safe_walk_nearby.helper_profiles ADD CONSTRAINT helper_profiles_consent_version_check
  CHECK (char_length(consent_version) BETWEEN 1 AND 64);
-- Change only the inventoried recipient FK. Existing rows are validated, never deleted.
ALTER TABLE safe_walk_nearby.alert_deliveries
  DROP CONSTRAINT alert_deliveries_recipient_id_fkey;
ALTER TABLE safe_walk_nearby.alert_deliveries ADD CONSTRAINT alert_deliveries_recipient_id_fkey
  FOREIGN KEY (recipient_id) REFERENCES auth.users(id) ON DELETE CASCADE;
'''
    # Constrain the name used by the ALTER as well as the semantic baseline above.
    preflight = preflight.replace('ALTER TABLE safe_walk_nearby.helper_profiles', '''DO $fk_name$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE
    conrelid='safe_walk_nearby.alert_deliveries'::regclass
    AND conname='alert_deliveries_recipient_id_fkey' AND contype='f') THEN
    RAISE EXCEPTION 'Unexpected recipient FK name; stop and review';
  END IF;
END $fk_name$;
ALTER TABLE safe_walk_nearby.helper_profiles''', 1)
    body = source[source.index('-- ---------------------------------------------------------------- tables'):]
    body = re.sub(r'extensions\.(st_\w+|geography|geometry)', r'public.\1', body)
    # The inventoried helper_locations_geog_gist index already covers this column.
    body = re.sub(r'create index if not exists helper_locations_geog_idx\n.*?;\n', '', body, flags=re.S)
    body = body.replace("array['anon', 'authenticated']", "array['anon', 'authenticated', 'service_role']")
    # Serialize same-account mutations before checking rate/quantity limits, including
    # the missing-row case. Contact mutations also share a lock so consuming a code
    # or checking the owner's/follower's limits cannot race across different accounts.
    pattern = re.compile(r'(create or replace function ([\w.]+)\(.*?as \$\$)(.*?)(\$\$;)', re.S)
    def lock_function(match):
        start, name, sql, end = match.groups()
        if 'v_uid uuid' in sql and not name.endswith(('list_mine', 'following', 'get_areas', 'fetch_alerts')):
            anchor = "raise exception 'not_authenticated' using errcode = '28000';\n  end if;"
            locks = ''
            if '.nearby_contact_' in name:
                locks += "\n  perform pg_advisory_xact_lock(hashtextextended('safe_walk_nearby:contacts', 0));"
            locks += "\n  perform pg_advisory_xact_lock(hashtextextended('safe_walk_nearby:user:' || v_uid::text, 0));"
            sql = sql.replace(anchor, anchor + locks, 1)
        return start + sql + end
    body = pattern.sub(lock_function, body)
    migration = header + before + preflight + body
    # Metadata-only verifier: reuse and extend the four-table catalog contract.
    verify = before.replace('$baseline$', '$verify$')
    verify = verify.replace("<> 4\n", "<> 8\n").replace("<> 20 THEN", "<> 37 THEN")
    verify = verify.replace("OR EXISTS (SELECT 1 FROM pg_proc WHERE pronamespace = target_schema)",
        "OR (SELECT count(*) FROM pg_proc WHERE pronamespace = target_schema) <> 1\n"
        "      OR to_regprocedure('safe_walk_nearby.purge_expired()') IS NULL")
    verify = verify.replace('Expected four ordinary tables, indexes, zero functions/policies/user triggers',
        'Expected eight ordinary tables, indexes, one private function, zero policies/user triggers')
    verify = verify.replace('Expected exactly the 20 design columns', 'Expected exactly the 37 backend columns')
    columns = '''    ('helper_areas', 'id', 'uuid', true, 'gen_random_uuid()'),
    ('helper_areas', 'user_id', 'uuid', true, NULL),
    ('helper_areas', 'center', 'geography', true, NULL),
    ('helper_areas', 'radius_m', 'integer', true, NULL),
    ('helper_areas', 'created_at', 'timestamptz', true, 'now()'),
    ('contact_invites', 'code_hash', 'text', true, NULL),
    ('contact_invites', 'owner_id', 'uuid', true, NULL),
    ('contact_invites', 'display_name', 'text', true, NULL),
    ('contact_invites', 'created_at', 'timestamptz', true, 'now()'),
    ('contact_invites', 'expires_at', 'timestamptz', true, NULL),
    ('trusted_contacts', 'id', 'uuid', true, 'gen_random_uuid()'),
    ('trusted_contacts', 'owner_id', 'uuid', true, NULL),
    ('trusted_contacts', 'contact_id', 'uuid', true, NULL),
    ('trusted_contacts', 'display_name', 'text', true, NULL),
    ('trusted_contacts', 'created_at', 'timestamptz', true, 'now()'),
    ('contact_invite_attempts', 'user_id', 'uuid', true, NULL),
    ('contact_invite_attempts', 'attempted_at', 'timestamptz', true, 'now()'),
'''
    verify = verify.replace("    ('helper_profiles', 'user_id', 'uuid'", columns + "    ('helper_profiles', 'user_id', 'uuid'", 1)
    verify = verify.replace("    ('helper_profiles', 'p', ARRAY['user_id']),", """    ('helper_areas', 'p', ARRAY['id']),
    ('contact_invites', 'p', ARRAY['code_hash']),
    ('trusted_contacts', 'p', ARRAY['id']),
    ('trusted_contacts', 'u', ARRAY['owner_id', 'contact_id']),
    ('helper_profiles', 'p', ARRAY['user_id']),""")
    verify = verify.replace("    ('helper_profiles', 'user_id', 'auth.users', 'id'),", """    ('helper_areas', 'user_id', 'safe_walk_nearby.helper_profiles', 'user_id'),
    ('contact_invites', 'owner_id', 'auth.users', 'id'),
    ('trusted_contacts', 'owner_id', 'auth.users', 'id'),
    ('trusted_contacts', 'contact_id', 'auth.users', 'id'),
    ('contact_invite_attempts', 'user_id', 'auth.users', 'id'),
    ('helper_profiles', 'user_id', 'auth.users', 'id'),""")
    verify = verify.replace("('alert_deliveries', 'recipient_id', 'safe_walk_nearby.helper_profiles', 'user_id')",
                            "('alert_deliveries', 'recipient_id', 'auth.users', 'id')")
    verify = verify.replace('<> 12 THEN', '<> 26 THEN').replace(
        'Expected exactly 4 PK, 5 FK, 1 UNIQUE and 2 CHECK constraints',
        'Expected exactly 7 PK, 10 FK, 2 UNIQUE and 7 CHECK constraints')
    verify = verify.replace("('helper_locations', 'accuracy_misnulloraccuracy_m>=0'), ('alerts', 'radius_m=500')", """('helper_locations', 'accuracy_misnulloraccuracy_m>=0'), ('alerts', 'radius_m=500'),
    ('helper_profiles', 'char_lengthconsent_version>=1andchar_lengthconsent_version<=64'),
    ('helper_areas', 'radius_m>=500andradius_m<=1000'),
    ('contact_invites', 'char_lengthdisplay_name>=1andchar_lengthdisplay_name<=20')""")
    # trusted_contacts has two CHECKs, verified independently below.
    extra = (ROOT / 'local_test/verify_backend_extra.sql').read_text(encoding='utf-8')
    functions = []
    for match in pattern.finditer(body):
        name = match.group(2)
        params = match.group(1).split('(', 1)[1].split(')\nreturns', 1)[0]
        sigtypes = []
        for param in params.split(','):
            if param.strip():
                sigtypes.append(re.sub(r' default .*', '', param.strip().split(' ', 1)[1]))
        signature = name + '(' + ','.join(sigtypes) + ')'
        digest = hashlib.md5(match.group(3).encode()).hexdigest()
        result = match.group(1).split('\nreturns ', 1)[1].split('\nlanguage ', 1)[0]
        result = re.sub(r'\s+', ' ', result).strip().lower()
        result = re.sub(r'\s*([(),])\s*', r'\1', result)
        names = [p.strip().split(' ', 1)[0] for p in params.split(',') if p.strip()]
        functions.append("    ('%s', '%s', %s, '%s', ARRAY[%s]::text[])" % (
            signature, digest, 'false' if name.startswith('safe_walk_nearby.') else 'true',
            result, ','.join("'%s'" % name for name in names)))
    extra = extra.replace('-- FUNCTION_MANIFEST', ',\n'.join(functions))
    verifier = '''-- GENERATED by local_test/generate_upgrade.py. Metadata only; invokes no RPC.
BEGIN TRANSACTION READ ONLY;
SET LOCAL search_path = pg_catalog;
SET LOCAL statement_timeout = '15s';
''' + verify + extra + "\nSELECT 'nearby backend catalog verified; not Live/device verification' AS result;\nROLLBACK;\n"
    # A failure in the postconditions rolls back the entire upgrade.
    migration = migration.rsplit('commit;', 1)[0] + '\n' + verify + extra + '\nCOMMIT;\n'
    behavior = (ROOT / 'local_test/10_test_nearby_helper.sql').read_text(encoding='utf-8')
    behavior = re.sub(r'extensions\.(st_\w+|geography|geometry)', r'public.\1', behavior)
    # Historical test predates contact sender_name; only sender_id must stay private.
    behavior = behavior.replace("!~* 'sender'", "!~* 'sender_id'")
    safety = '''DO $local_only$
BEGIN
  IF current_database() !~ '^nearby_upgrade_[a-f0-9]{12}$'
      OR host(inet_server_addr()) <> '127.0.0.1' THEN
    RAISE EXCEPTION 'Only a disposable local upgrade-test database is allowed';
  END IF;
END $local_only$;
'''
    behavior = '-- GENERATED adaptation of the historical behavior suite for the upgrade.\n' + safety + behavior
    return {MIGRATION: migration, VERIFIER: verifier,
            ROOT / 'local_test/30_test_upgraded_backend.sql': behavior}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in build().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated SQL: {path.name}')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    print('Generated SQL is current' if args.check else 'Generated migration and verifier')
